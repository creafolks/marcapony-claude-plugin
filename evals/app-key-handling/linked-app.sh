)
```
- Input: `{ formId: string; formMode: string; submissionData: Record<string, unknown>; name?: string; email?: string; message?: string }`
- Returns: `WriteResult<FormSubmissionReceipt>`
- The contact form of this site has formId `frm_contact`.

